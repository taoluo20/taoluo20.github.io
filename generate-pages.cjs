const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname);
const manifestFile = path.join(root, 'generated-pages.json');
const marker = '<!-- Generated by generate-pages.cjs; edit the root index.html and site-data.js. -->';

function ownedFile(relative) {
  if (relative !== '404.html' && !/^(?:[a-zA-Z0-9_-]+\/)+index\.html$/.test(relative)) throw new Error(`Unsafe generated page: ${relative}`);
  const absolute = path.resolve(root, relative);
  if (!absolute.startsWith(root + path.sep)) throw new Error('Generated page must stay inside this website.');
  return absolute;
}

function generatePages() {
  const context = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, 'site-data.js'), 'utf8'), context);
  const data = context.window.PORTFOLIO;
  const template = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const previous = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')) : [];
  if (!Array.isArray(previous)) throw new Error('Generated page manifest must be an array.');
  const routes = new Map();
  const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
  const slug = value => {
    if (typeof value !== 'string' || !/^[a-zA-Z0-9_-]+$/.test(value)) throw new Error(`Invalid page id: ${value}`);
    return value;
  };
  const add = (route, title) => {
    if (routes.has(route)) throw new Error(`Duplicate page route: ${route}`);
    routes.set(route, title + ' — Tao Luo');
  };
  for (const [section, title] of [['demo', 'Demo'], ['vfx', 'VFX'], ['photography', 'Photography'], ['about', 'About me'], ['blog', 'Blog'], ['contact', 'Contact']]) add(`/${section}/`, title);
  for (const project of data.projects) add(`/vfx/${slug(project.id)}/`, data.release === 'wip' ? 'VFX' : project.title);
  for (const project of data.posts) {
    const base = `/blog/${slug(project.id)}/`;
    add(base, project.title);
    project.entries.forEach((entry, index) => {
      const title = `${project.title} — post #${String(index + 1).padStart(3, '0')}`;
      add(`${base}${slug(entry.id)}/`, title);
      for (const alias of entry.aliases || []) add(`${base}${slug(alias)}/`, title);
    });
  }
  const pages = new Map([...routes].map(([route, title]) => [route.slice(1) + 'index.html', title]));
  pages.set('404.html', 'Page not found — Tao Luo');
  const generatedFiles = [...pages.keys()].sort();
  for (const [relative, title] of pages) {
    const absolute = ownedFile(relative);
    const old = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : null;
    if (old !== null && !previous.includes(relative) && !old.includes(marker)) throw new Error(`Refusing to overwrite a page outside the generated manifest: ${relative}`);
    const html = template.replace(/<title>[\s\S]*?<\/title>/i, () => `<title>${escape(title)}</title>`).replace('<!doctype html>', '<!doctype html>\n' + marker);
    if (html !== old) {
      fs.mkdirSync(path.dirname(absolute), { recursive: true });
      fs.writeFileSync(absolute, html);
    }
  }
  for (const relative of previous) {
    if (pages.has(relative)) continue;
    const absolute = ownedFile(relative);
    if (fs.existsSync(absolute)) {
      if (!fs.readFileSync(absolute, 'utf8').includes(marker)) throw new Error(`Refusing to delete an edited page: ${relative}`);
      fs.unlinkSync(absolute);
    }
  }
  const manifest = JSON.stringify(generatedFiles, null, 2) + '\n';
  if (!fs.existsSync(manifestFile) || fs.readFileSync(manifestFile, 'utf8') !== manifest) fs.writeFileSync(manifestFile, manifest);
  return generatedFiles;
}

module.exports = { generatePages };
if (require.main === module) console.log(`Generated ${generatePages().length} static page entries for clean URLs.`);
